  const sheet = makeSheet(H_G, rows);
  const fn = new Function('SpreadsheetApp', code + '\nreturn { findColumns, addNextStage };');
  const api = fn({ getActiveSpreadsheet: () => ({ toast: () => {} }) });
  const idx = api.findColumns(sheet);
  api.addNextStage(sheet, idx);

  const got = sheet._grid.slice(1, 1 + rows.length)
    .map(r => `${r[2]}:${r[6] || '-'}`).join(', ');
  const ok = got === expect;
  if (ok) pass++;
