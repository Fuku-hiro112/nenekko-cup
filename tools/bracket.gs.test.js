/**
 * bracket.gs のロジックを、スプレッドシートを模して検証する。
 *
 *     node tools/bracket.gs.test.js
 *
 * GAS は Google 側でしか動かないので、使っている API だけ偽物を用意している。
 * **bracket.gs を直したら、これを流してから貼り直すこと。**
 *
 * 大会方式は3段階（予選 → 順位決定戦 → 決勝＋最下位決定戦）。
 * どの卓も3戦打ち、3戦の合計点で順位を決める。仕様は docs/detail-design.md 章7-1。
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'bracket.gs');
const code = fs.readFileSync(SRC, 'utf8');

function makeSheet(header, rows) {
  const grid = [header, ...rows.map(r => {
    const line = new Array(header.length).fill('');
    r.forEach((v, i) => line[i] = v);
    return line;
  })];
  return {
    _grid: grid,
    _toasts: [],
    getLastRow: () => grid.length,
    getLastColumn: () => header.length,
    getRange(row, col, numRows, numCols) {
      return {
        getValues: () => grid.slice(row - 1, row - 1 + numRows).map(r => r.slice(col - 1, col - 1 + numCols)),
        // **列の位置を守ること。** bracket.gs は必要な列だけを書くので、
        // 行をまるごと差し替える偽物だと、実際と違う結果を検証してしまいます。
        setValues: (vals) => {
          vals.forEach((v, i) => {
            const r = row - 1 + i;
            if (!grid[r]) grid[r] = new Array(header.length).fill('');
            v.forEach((cell, j) => grid[r][col - 1 + j] = cell);
          });
        },
        setBackground: () => {},
        getColumn: () => col,
        getSheet: () => null,
      };
    },
  };
}

/**
 * 1件流す。`expect` は「段/卓/名前」を並べた文字列。
 * `expectMessage` を渡すと、返ってきた理由にその言葉が含まれるかも見る。
 */
function run(name, header, rows, expect, expectMessage) {
  const sheet = makeSheet(header, rows);
  const SpreadsheetApp = { getActiveSpreadsheet: () => ({ toast: (m) => sheet._toasts.push(m) }) };
  const fn = new Function('SpreadsheetApp', code + '\nreturn { findColumns, addNextStage, parseScore };');
  const api = fn(SpreadsheetApp);

  const idx = api.findColumns(sheet);
  const res = api.addNextStage(sheet, idx);

  const added = sheet._grid.slice(1 + rows.length);
  const summary = added.length
    ? added.map(r => `${r[idx.round]}/${r[idx.table]}/${r[idx.name]}`).join(', ')
    : '(追加なし)';
  // 作れなかったときは、理由がひとこと返ってくること
  if (!added.length && (!res || !res.message)) console.log('      !! 理由が返っていません');

  let ok = summary === expect;
  if (ok && expectMessage) {
    ok = String(res && res.message).indexOf(expectMessage) >= 0;
    if (!ok) console.log(`      !! 理由に「${expectMessage}」が入っていません`);
  }
  console.log(`${ok ? 'OK  ' : '!!  '} ${name}`);
  console.log(`      期待: ${expect}`);
  console.log(`      実際: ${summary}`);
  if (res && res.message) console.log(`      ひとこと: ${res.message}`);
  return ok;
}

